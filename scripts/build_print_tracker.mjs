import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';

const root=process.env.FRIESGO_OUTPUT_DIR;
if(!root)throw new Error('Run through scripts/reproduce.py --rebuild');
const qa=path.join(root,'print_tracking_qa');
await fs.mkdir(qa,{recursive:true});
const accounts=JSON.parse(await fs.readFile(path.join(root,'canonical_accounts.json'),'utf8'));
const names=accounts.map(a=>a.display_name||a.name);
if(accounts.length!==20||names.length!==20)throw new Error('Expected 20 accounts');
const wb=Workbook.create();
const sh=wb.worksheets.add('打印记录');
sh.showGridLines=false;
const all=sh.getRange('A1:I26');
all.format.font={name:'Arial',size:10.5,color:'#000000'};
all.format.verticalAlignment='center';
all.format.fill='#FFFFFF';
const widths=[42,25,26,27,25,29,27,25,49];
const cols='ABCDEFGHI';
widths.forEach((mm,i)=>sh.getRange(`${cols[i]}1:${cols[i]}26`).format.columnWidthPx=mm/25.4*96);
sh.getRange('A1').values=[['FriesGo 客户开发操作记录']];
sh.getRange('A1').format.font={name:'Arial',size:15,bold:true,color:'#000000'};
sh.getRange('A1:I1').format.rowHeight=27;
sh.getRange('A2').values=[['业务员：________________    记录周期：________________']];
sh.getRange('A2:I2').format.rowHeight=21;
sh.getRange('A3').values=[['格内填日期＋动作，如“10/23 发”。查＝查找/核对　加＝添加　发＝已发消息　回＝有回复；空白＝未操作。']];
sh.getRange('A3:I3').format.rowHeight=20;
sh.getRange('A3').format.font={name:'Arial',size:10,color:'#404040'};
sh.getRange('A4:I4').values=[['公司名称','网站','邮箱','WhatsApp','LinkedIn','Facebook / IG','Zalo / 微信','电话','下次跟进 / 备注']];
sh.getRange('A4:I4').format={font:{name:'Arial',size:10.5,bold:true,color:'#000000'},fill:'#EEEEEE',horizontalAlignment:'center',verticalAlignment:'center',rowHeight:27,wrapText:true};
sh.getRange('A5:A24').values=names.map(n=>[n]);
sh.getRange('A5:I24').format.rowHeight=21;
sh.getRange('A5:A24').format.wrapText=true;
sh.getRange('A5:A24').format.horizontalAlignment='left';
sh.getRange('B5:I24').format.horizontalAlignment='center';
sh.getRange('B5:I24').format.wrapText=true;
sh.getRange('A4:I24').format.borders={preset:'all',style:'thin',color:'#B8B8B8'};
sh.getRange('A25').values=[['渠道列用于记录操作；未核实的账号先查找，具体网址、号码及邮箱参照客户档案。']];
sh.getRange('A25').format.font={name:'Arial',size:9.5,color:'#555555'};
sh.getRange('A25:I25').format.rowHeight=19;
sh.getRange('A26:I26').format.rowHeight=6;
sh.freezePanes.freezeRows(4);
sh.freezePanes.freezeColumns(1);
wb.recalculate();
const check=await wb.inspect({kind:'table',range:"'打印记录'!A4:I24",include:'values',tableMaxRows:21,tableMaxCols:9,maxChars:5500});
await fs.writeFile(path.join(qa,'inspect.ndjson'),check.ndjson);
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:20},summary:'final error scan',maxChars:1000});
await fs.writeFile(path.join(qa,'errors.ndjson'),errors.ndjson);
const preview=await wb.render({sheetName:'打印记录',range:'A1:I25',scale:1.5,format:'png'});
await fs.writeFile(path.join(qa,'worksheet.png'),new Uint8Array(await preview.arrayBuffer()));
const output=await SpreadsheetFile.exportXlsx(wb);
await output.save(path.join(root,'06_业务员操作记录_一页横版.xlsx'));
console.log(JSON.stringify({accounts:names.length,recordCells:160,exported:true}));
